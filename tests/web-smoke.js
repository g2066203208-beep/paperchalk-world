const fs=require('fs');
function assert(c,m){if(!c)throw new Error(m)}
const read=p=>fs.readFileSync(p,'utf8');
const html=read('index.html'),game=read('src/game.js'),engine=read('src/engine3d/World3DEngine.js'),content=read('src/content/game-content.js'),terrain=read('src/terrain/terrain-runtime.js'),mesher=read('src/terrain/voxel-block-mesh.js');
assert(html.includes('voxel3d-r3'),'3D voxel build key missing');
assert(html.includes('id="threeWorldLayer"'),'Three.js host missing');
assert(terrain.includes('class TerrainWorld'),'TerrainWorld missing');
assert(terrain.includes('chunkSize=16'),'16^3 voxel chunks missing');
assert(terrain.includes('generateVoxel(gx,gy,gz)'),'3D voxel generation missing');
assert(terrain.includes('peekVoxel(gx,gy,gz)'),'non-loading 3D voxel lookup missing');
assert(terrain.includes('collidesAABB(x,y,z'),'3D voxel collision missing');
assert(terrain.includes('dimensions:3')&&terrain.includes('infinite:true'),'infinite 3D terrain stats missing');
assert(mesher.includes('buildVoxelChunkGeometry'),'3-axis greedy voxel mesher missing');
assert(mesher.includes('for(let d=0;d<3;d++)'),'mesher does not sweep 3 axes');
assert(engine.includes("infinite-3d-voxel-terrain"),'3D chunk renderer missing');
assert(engine.includes("worldMode:'infinite-voxel-3d'"),'wrong world mode');
assert(engine.includes("terrainMode:'streamed-3d-voxel-chunks'"),'wrong terrain mode');
assert(engine.includes('_raycastVoxel(ray,maxDistance=8)'),'voxel DDA raycast missing');
assert(game.includes("keys.has('KeyW')")&&game.includes("keys.has('KeyS')"),'forward/back movement missing');
assert(game.includes("moveAxis('z'"),'Z-axis movement missing');
assert(game.includes('placeTerrainCell')&&game.includes('digTerrainCell'),'3D dig/place missing');
assert(content.includes("mode:'infinite-voxel-3d'"),'3D voxel content mode missing');
assert(content.includes('visibleChunkRadiusXZ'),'3D streaming radius missing');
assert(content.includes('interactionRowZ:0'),'configured interaction row missing');
assert(game.includes("interaction-row-only"),'interaction-row editing guard missing');
assert(engine.includes("mode:'sun-only'")&&engine.includes("background:'black'"),'sun-only black-world lighting missing');
assert(engine.includes('sun.castShadow=true'),'sun shadowing missing');
assert(engine.includes("visible-sun"),'visible sun mesh missing');
assert(engine.includes('sun.intensity=daylight*3.8'),'daylight sun intensity missing');
assert(engine.includes('mesh.receiveShadow=true;mesh.castShadow=true'),'voxel chunks must cast and receive sunlight shadows');
