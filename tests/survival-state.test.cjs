'use strict';
const assert=require('node:assert/strict');
const {create,KEY,RATES}=require('../site/game/survival-state.js');
const memory=new Map();
const storage={getItem:k=>memory.get(k)??null,setItem:(k,v)=>memory.set(k,v)};
const game=create({storage});
assert.deepEqual(game.snapshot().stats.health,{current:100,max:100});
assert.deepEqual(game.snapshot().stats.hunger,{current:100,max:100});
assert.deepEqual(game.snapshot().stats.sanity,{current:100,max:100});
assert.equal(RATES.hungerPerActiveMinute,.25);
assert.equal(game.advance(4*60*1000),true);
assert.equal(game.snapshot().stats.hunger.current,99);
assert.equal(game.apply({type:'damage',amount:15}),true);
assert.equal(game.snapshot().stats.health.current,85);
assert.equal(game.apply({type:'heal',amount:500}),true);
assert.equal(game.snapshot().stats.health.current,100);
assert.equal(game.apply({type:'stress',amount:28}),true);
assert.equal(game.snapshot().stats.sanity.current,72);
assert.equal(game.apply({type:'recover-sanity',amount:3}),true);
assert.equal(game.snapshot().stats.sanity.current,75);
assert.equal(game.apply({type:'eat',amount:16}),true);
assert.equal(game.snapshot().stats.hunger.current,100);
assert.equal(game.apply({type:'exert',amount:13}),true);
assert.equal(game.snapshot().stats.hunger.current,87);
assert.equal(game.apply({type:'damage',amount:-1}),false);
assert.equal(game.apply({type:'not-an-event',amount:20}),false);
assert.equal(game.snapshot().stats.sanity.current,75,'sanity changes only from explicit events');
assert.equal(game.advance(-3),false,'time never rolls backwards');
assert.equal(game.persist(),true);
assert.ok(memory.has(KEY));
const resumed=create({storage});
assert.equal(resumed.snapshot().stats.health.current,100);
assert.equal(resumed.snapshot().stats.hunger.current,87);
assert.equal(resumed.snapshot().stats.sanity.current,75);
assert.equal(resumed.setStats({health:{current:80,max:125},hunger:{current:1,max:80}}),true);
assert.deepEqual(resumed.snapshot().stats.health,{current:80,max:125});
assert.equal(resumed.advance(8*60*1000),true);
assert.equal(resumed.snapshot().stats.hunger.current,0);
assert.equal(resumed.snapshot().stats.health.current,78,'starvation starts only after hunger reaches zero');
assert.equal(resumed.apply({type:'heal',amount:100000}),true);
assert.equal(resumed.snapshot().stats.health.current,125,'HP clamped to max');
assert.equal(resumed.apply({type:'damage',amount:100000}),true);
assert.equal(resumed.snapshot().stats.health.current,0,'HP never negative');
const events=[];
const unsubscribe=resumed.subscribe((snap,source)=>events.push({health:snap.stats.health.current,source}));
assert.equal(resumed.apply({type:'heal',amount:12}),true);
unsubscribe();
assert.equal(events.length,1);
assert.equal(events[0].source,'heal');
resumed.reset();
assert.equal(resumed.snapshot().stats.health.current,100);
assert.equal(create({storage}).snapshot().stats.hunger.current,100,'reset is persisted');
console.log('PASS survival state: exact damage/heal/sanity, timed hunger, starvation, persistence, clamping, events');
