test('stripe normal translation is exactly periodic',()=>{
  const stripe=(x,y,p)=>((x+y+p)%80+80)%80<36;
  for(let y=0;y<21;y++)for(let x=0;x<84;x++)assert.equal(stripe(x,y,0),stripe(x+40,y+40,0));
});
