import assert from 'node:assert/strict';
import fs from 'node:fs';
const model=JSON.parse(fs.readFileSync('site/pixel-lab/model.json','utf8'));
const policy=JSON.parse(fs.readFileSync('site/pixel-lab/brush-policy.json','utf8'));
assert.equal(model.format,'pixel-lab-neural-inpaint-v1');
assert.equal(model.input_features,327);
assert.equal(model.w1.length,327);
assert.equal(model.w1[0].length,56);
assert.equal(model.w2.length,56);
assert.equal(model.w2[0].length,12);
assert.ok(model.metrics.heldout_masked_accuracy>=0&&model.metrics.heldout_masked_accuracy<=1);
assert.ok(model.examples.length>2);
assert.ok(model.examples.every(e=>e.pixels.length===256));
assert.ok(model.sources.some(x=>x.image_count>=25));
for(const row of model.w1)assert.ok(row.every(Number.isFinite));
assert.equal(policy.actions.length,5);
assert.ok(Object.keys(policy.q).length>5);
assert.ok(policy.metrics.stroke_reduction>0);
console.log('PASS real neural model weights, heldout CC0 sprite samples, and learned Q policy');
