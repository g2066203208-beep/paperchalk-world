/* Undo prior auto-added shorts on the BASE with a non-destructive
 * backup. All 17 original PSD layers and user paint/bones must survive. */
'use strict';
const assert=require('node:assert/strict'),{chromium}=require('playwright');
(async()=>{
 const browser=await chromium.launch({headless:true});
 try{
  const page=await browser.newPage({viewport:{width:1200,height:900}}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  const url='http://127.0.0.1:8134/character-editor/?character=female-06&side=front';
  await page.goto(url,{waitUntil:'load'});
  await page.waitForFunction(()=>window.PaperchalkStudio?.current==='female-06'&&
   window.PaperchalkPartRigStudio?.state?.active&&
   window.characterEditor.S.layers.front.filter(x=>x.sourcePart).length===17,
   null,{timeout:50000});
  // Simulate the actual broken 18th ArtMesh generated by a previous release.
  const seeded=await page.evaluate(async()=>{
   const ed=window.characterEditor,parts=ed.S.layers.front;
   const legs=parts.find(p=>p.partId==='legwear'),arm=parts.find(p=>p.partId==='handwear_l');
   if(!legs||!arm)throw Error('original source legs/left hand missing');
   arm.opacity=.63;
   const phantom=ed.layer('自动叠加的旧短裤',legs.canvas,420,415,false);
   phantom.sourcePart=true;phantom.partId='pants_overlay';phantom.role='psd-part';
   parts.push(phantom);await ed.save();
   const rig=JSON.parse(JSON.stringify(window.PaperchalkPartRigStudio.state.model));
   rig.parts.pants_overlay={...structuredClone(rig.parts.legwear),
      id:'pants_overlay',name:'自动叠加的旧短裤',kind:'pants-bound',parentId:'pelvis'};
   rig.layerOrder=[...rig.layerOrder,'pants_overlay'];
   rig.partCount=Object.keys(rig.parts).length;
   const db=await new Promise((yes,no)=>{
    const r=indexedDB.open('paperchalk-dev-characters-v1',1);
    r.onsuccess=()=>yes(r.result);r.onerror=()=>no(r.error);
   });
   await new Promise((yes,no)=>{
    const tx=db.transaction('kv','readwrite');
    tx.objectStore('kv').put(rig,'part-rig:female-06:front');
    tx.oncomplete=yes;tx.onerror=()=>no(tx.error);
   });db.close();
   return {count:parts.filter(p=>p.sourcePart).length,opacity:arm.opacity};
  });
  assert.deepEqual(seeded,{count:18,opacity:.63});
  await page.reload({waitUntil:'load'});
  await page.waitForFunction(()=>window.PaperchalkStudio?.current==='female-06'&&
   window.PaperchalkPartRigStudio?.state?.active&&
   window.characterEditor.S.layers.front.filter(x=>x.sourcePart).length===17,
   null,{timeout:50000});
  const restored=await page.evaluate(async()=>{
   const layers=window.characterEditor.S.layers.front.filter(x=>x.sourcePart);
   const db=await new Promise((yes,no)=>{
    const r=indexedDB.open('paperchalk-dev-characters-v1',1);
    r.onsuccess=()=>yes(r.result);r.onerror=()=>no(r.error);
   });
   const load=key=>new Promise((yes,no)=>{const tx=db.transaction('kv','readonly'),r=tx.objectStore('kv').get(key);r.onsuccess=()=>yes(r.result);r.onerror=()=>no(r.error)});
   const archive=await load('archived-auto-pants:female-06:front');
   const rig=await load('part-rig:female-06:front');
   db.close();
   return {ids:layers.map(p=>p.partId),opacity:layers.find(p=>p.partId==='handwear_l')?.opacity,
      archive:!!archive?.texture&&!!archive?.rig,
      cleaned:!rig?.parts?.pants_overlay};
  });
  assert.equal(restored.ids.length,17);
  assert.ok(!restored.ids.includes('pants_overlay'));
  assert.equal(restored.opacity,.63);
  assert.equal(restored.archive,true,'all old auto-shorts edits archived for recovery');
  assert.equal(restored.cleaned,true);
  await page.reload({waitUntil:'load'});
  await page.waitForFunction(()=>window.PaperchalkStudio?.current==='female-06'&&
   window.characterEditor.S.layers.front.filter(x=>x.sourcePart).length===17,
   null,{timeout:50000});
  assert.deepEqual(errors,[]);
  console.log('PASS previous base shorts reverted 18→17, archived bytes+rig, real body and user edits preserved across reload');
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exit(1)});
