import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs';
const out='artifacts/film-projector-blockout';
fs.mkdirSync(out,{recursive:true});
const browser=await chromium.launch({headless:true,args:['--no-sandbox','--disable-dev-shm-usage','--use-angle=swiftshader','--enable-unsafe-swiftshader','--enable-webgl']});
try{
 const page=await browser.newPage({viewport:{width:1600,height:900},deviceScaleFactor:1});
 const errors=[];
 page.on('pageerror',e=>errors.push(String(e)));
 await page.goto('http://127.0.0.1:4173/film-projector/blockout.html',{waitUntil:'domcontentloaded'});
 await page.waitForFunction(()=>document.querySelector('#viewport')?.dataset.renderer==='three-2p5d-paper-planes',{timeout:20000});
 const audit=await page.evaluate(()=>window.PaperStageAudit);
 assert.equal(audit.solidMeshes,0,'No projector solid meshes allowed');
 assert.ok(audit.paperPlanes>20,'Paper planes must remain separate');
 assert.equal(await page.locator('#viewport').getAttribute('data-shadows'),'true');
 assert.equal(await page.locator('#selection').innerText(),'胶片 02 / 07');
 await page.waitForTimeout(800);
 await page.screenshot({path:out+'/01-paper-stage-layout-grey.png'});
 await page.locator('#portrait').click();
 await page.waitForTimeout(700);
 await page.screenshot({path:out+'/02-paper-stage-original-character.png'});
 await page.locator('#next').click();
 await page.waitForTimeout(400);
 assert.equal(await page.locator('#selection').innerText(),'胶片 03 / 07');
 await page.screenshot({path:out+'/03-reel-film-step.png'});
 await page.locator('#lighting').click();
 assert.equal(await page.locator('#lighting').getAttribute('aria-pressed'),'false');
 await page.waitForTimeout(320);
 await page.screenshot({path:out+'/04-ambient-light-off.png'});
 await page.locator('#portrait').click();
 await page.locator('#lighting').click();
 await page.locator('#guides').click();
 assert.equal(await page.locator('#labels').isVisible(),true);
 await page.waitForTimeout(200);
 await page.screenshot({path:out+'/05-layers-guides.png'});
 assert.deepEqual(errors,[],'no unhandled page Javascript errors');
 console.log(JSON.stringify({result:'PASS',renderer:'ThreeJS',geometry:'100% flat 2D cutouts',paperPlanes:audit.paperPlanes,solidMeshes:audit.solidMeshes,shadowMaps:true,screenshots:out}));
}finally{await browser.close()}
