import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs';
const out='artifacts/card-battle-tactile';
fs.mkdirSync(out,{recursive:true});
const browser=await chromium.launch({headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
try{
 const page=await browser.newPage({viewport:{width:1600,height:900},deviceScaleFactor:1});
 const errors=[];
 page.on('pageerror',err=>errors.push(String(err)));
 await page.goto('http://127.0.0.1:4173/card-battle/',{waitUntil:'networkidle'});
 await page.locator('button.action-card').first().waitFor({timeout:18000});
 assert.equal(await page.locator('.tick-row').count(),3,'the two combatants share one 10-step ruler');
 assert.equal(await page.locator('button.action-card').count(),4,'the combat engine starts with four actions');
 assert.equal(await page.locator('.fighter').count(),2,'simple 1v1 battle only');
 for(const id of ['enemy-portrait','ally-portrait']){
  const ok=await page.locator('#'+id+' img').evaluate(img=>img.complete&&img.naturalWidth>0);
  assert.equal(ok,true,'existing GitHub card art loads in '+id);
 }
 const style=await page.evaluate(()=>getComputedStyle(document.documentElement).getPropertyValue('--wood'));
 assert.ok(style.includes('data:image/jpeg'),'procedural wood material is generated');
 await page.screenshot({path:out+'/01-table-opening-desktop.png',fullPage:true});
 const first=page.locator('button.action-card').first();
 await first.hover();
 await page.waitForTimeout(270);
 await page.screenshot({path:out+'/02-paper-card-hover.png'});
 await first.click();
 await page.locator('.tick.friend[data-tick="1"]').click();
 assert.ok(await page.locator('.tick.friend.active').count()>0,'a selected hand card places a real scheduled action');
 await page.screenshot({path:out+'/03-timeline-action-arranged.png'});
 await page.locator('#execute').click();
 await page.waitForTimeout(2850);
 assert.equal(await page.locator('#round').innerText(),'第 2 轮','ten combat ticks advance the actual game round');
 await page.screenshot({path:out+'/04-round-executed.png'});
 await page.locator('#restart').click();
 const drag=page.locator('button.action-card').first();
 const rect=await drag.boundingBox();
 const target=await page.locator('.tick.friend[data-tick="1"]').boundingBox();
 assert.ok(rect&&target);
 await page.mouse.move(rect.x+rect.width/2,rect.y+rect.height/2);
 await page.mouse.down();
 await page.mouse.move(target.x+target.width/2,target.y+target.height/2,{steps:14});
 await page.mouse.up();
 await page.waitForTimeout(270);
 assert.ok(await page.locator('.tick.friend.active').count()>0,'drag and drop physically places a real card');
 await page.screenshot({path:out+'/05-drag-placement.png'});
 assert.deepEqual(errors,[],'no uncaught browser errors');
 const mobile=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1});
 const mobileErrors=[];
 mobile.on('pageerror',err=>mobileErrors.push(String(err)));
 await mobile.goto('http://127.0.0.1:4173/card-battle/',{waitUntil:'networkidle'});
 await mobile.locator('button.action-card').first().waitFor();
 assert.equal(await mobile.locator('.tick-row').count(),3);
 await mobile.screenshot({path:out+'/06-phone-layout.png',fullPage:true});
 assert.deepEqual(mobileErrors,[],'mobile game has no uncaught errors');
 console.log(JSON.stringify({status:'PASS',mode:'inscription-inspired original 1v1 desk',screenshots:6,hand:4,lanes:2,sharedTicks:10}));
}finally{await browser.close();}
