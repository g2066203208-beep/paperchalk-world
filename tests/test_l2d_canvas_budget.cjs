'use strict';
const assert=require('node:assert/strict');
const {backingSize,DEFAULTS}=require('../site/l2d/canvas-budget.js');
assert.deepEqual(backingSize(0,400,2),{width:0,height:0,scale:0});
assert.deepEqual(backingSize(1024,1024,2),{width:2048,height:2048,scale:2});
assert.deepEqual(backingSize(500,500,3),{width:1000,height:1000,scale:2});
assert.deepEqual(backingSize(400,200,1),{width:400,height:200,scale:1});
const huge=backingSize(1800,3200,3);
assert.ok(huge.width>0&&huge.height>0,'large displays must never freeze the rig');
assert.ok(huge.width<=DEFAULTS.maxDimension&&huge.height<=DEFAULTS.maxDimension);
assert.ok(huge.width*huge.height<=DEFAULTS.maxPixels);
assert.ok(Math.abs(huge.width/huge.height-1800/3200)<.001,'preserve original ratio');
const wide=backingSize(3600,600,2);
assert.ok(wide.width>0&&wide.height>0);
assert.ok(Math.abs(wide.width/wide.height-6)<.01,'wide actor must not stretch');
assert.ok(wide.width*wide.height<=DEFAULTS.maxPixels);
const normal=backingSize(922,922,2);
assert.equal(normal.width,1844,'existing cinematic size remains unchanged');
console.log('PASS scalable DPR-correct L2D backing stores, large canvas freeze and memory budget');
