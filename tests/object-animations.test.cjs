'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const ctx=vm.createContext({window:{},Math,Map,Object,Number,Error});
vm.runInContext(fs.readFileSync(path.join(__dirname,'../site/card-battle/engine/object-animations.js'),'utf8'),ctx);
const engine=ctx.window.PaperchalkObjectAnimations.create();
engine.enter('tree-1',0,{duration:.5});
const birth=engine.sample('tree-1',0);
assert.equal(birth.phase,'enter');
assert.ok(birth.scale<.05,'starts small rather than instantly appearing at full size');
const middle=engine.sample('tree-1',.3);
assert.ok(middle.scale>1,'overshoots naturally for playful spring animation');
assert.equal(engine.sample('tree-1',.51).scale,1);
engine.pulse('tree-1',.6,{duration:.4,strength:.14});
assert.ok(engine.sample('tree-1',.8).scale>1,'a terrain change briefly bulges');
engine.exit('tree-1',1.2,{duration:.38});
assert.equal(engine.sample('tree-1',1.2).phase,'exit');
assert.ok(engine.sample('tree-1',1.39).scale<1,'a defeated object shrinks before removal');
assert.equal(engine.finished('tree-1',1.39),false);
assert.equal(engine.finished('tree-1',1.59),true);
assert.equal(engine.sample('tree-1',1.59).phase,'gone');
engine.clear('tree-1');
assert.equal(engine.sample('tree-1',2).phase,'steady');
engine.enter('tile-0:0',2,{delay:.2,duration:.5});
assert.equal(engine.sample('tile-0:0',2.1).phase,'queued');
assert.equal(engine.sample('tile-0:0',2.8).scale,1);
const reduced=ctx.window.PaperchalkObjectAnimations.create({reducedMotion:true});
reduced.enter('card',0);
assert.equal(reduced.sample('card',0).scale,1);
reduced.exit('card',1);
assert.equal(reduced.sample('card',1).scale,1);
engine.reset();
assert.equal(engine.stats(3).tracked,0);
console.log('OBJECT_ANIMATIONS_OK spring_spawn spring_exit land_pivot_motion pulse stagger reduced_motion');
