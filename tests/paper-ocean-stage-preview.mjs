import { chromium } from 'playwright';
import { strict as assert } from 'node:assert';
import { mkdirSync } from 'node:fs';
const dir='artifacts/paper-ocean';mkdirSync(dir,{recursive:true});
const browser=await chromium.launch({headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
try{
 const page=await browser.newPage({viewport:{width:1920,height:1080},deviceScaleFactor:1});
 page.on('pageerror',e=>console.error('PAPER_DEPTH_PAGE_ERROR',String(e)));
 await page.goto('http://127.0.0.1:8765/paper-depth-preview.html',{waitUntil:'domcontentloaded',timeout:60000});
 await page.waitForFunction(()=>window.PaperWorldPaperOceanRenderer?.inspect?.().imagesLoaded,{timeout:30000});
 let inspect=await page.evaluate(()=>window.PaperWorldPaperOceanRenderer.inspect());
 assert.equal(inspect.active,true);assert.equal(inspect.perspective,false);
 assert.equal(inspect.layerCount,7);assert.equal(inspect.allLayersMounted,true);assert.equal(inspect.level,1);
 await page.screenshot({path:dir+'/depth-01-village-1920x1080.png'});
 await page.locator('#paper-depth-next').click();
 inspect=await page.evaluate(()=>window.PaperWorldPaperOceanRenderer.inspect());
 assert.equal(inspect.level,2);
 await page.waitForTimeout(1500);
 await page.screenshot({path:dir+'/depth-02-fields-1920x1080.png'});
 for(let i=0;i<5;i++)await page.locator('#paper-depth-next').click();
 inspect=await page.evaluate(()=>window.PaperWorldPaperOceanRenderer.inspect());
 assert.equal(inspect.level,7);assert.equal(inspect.current,'throne');
 await page.waitForTimeout(1500);
 await page.screenshot({path:dir+'/depth-07-boss-1920x1080.png'});
 await page.locator('#paper-depth-next').click();
 assert.equal((await page.evaluate(()=>window.PaperWorldPaperOceanRenderer.inspect())).finished,true);
 await page.locator('#paper-depth-reset').click();
 assert.equal((await page.evaluate(()=>window.PaperWorldPaperOceanRenderer.inspect())).level,1);
 console.log('PAPER_DEPTH_REAL_GAME_PROOF',JSON.stringify(inspect));
}finally{await browser.close()}
