'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const ctx=vm.createContext({window:{},Math,Map,Set,Array,Object,Number,Error});
vm.runInContext(fs.readFileSync(path.join(__dirname,'../site/card-battle/engine/profession-decks.js'),'utf8'),ctx);
const instance=ctx.window.PaperchalkProfessionDecks.create({maxHand:10,openingDraw:5,unlocked:['warrior'],seed:618231});
const first=instance.snapshot();
assert.equal(first.classes.length,7);
assert.equal(first.count,5);
assert.equal(first.maxHand,10);
assert.equal(first.classes.find(c=>c.id==='warrior').handCount,5);
assert.equal(first.classes.filter(c=>c.unlocked).length,1);
assert.equal(instance.draw('engineer').reason,'locked-class');
const known=first.classes.find(c=>c.id==='warrior').top;
assert.equal(instance.playTop('warrior','invalid').reason,'not-top');
for(let i=0;i<5;i++)assert.equal(instance.draw('warrior').ok,true);
assert.equal(instance.snapshot().count,10);
assert.equal(instance.draw('warrior').reason,'hand-full');
let top=instance.snapshot().classes.find(c=>c.id==='warrior').top;
assert.equal(instance.playTop('warrior',top.instance).ok,true);
assert.equal(instance.snapshot().count,9);
assert.equal(instance.snapshot().locked,true);
assert.equal(instance.draw('warrior').reason,'draw-locked');
assert.equal(instance.draw('warrior',{special:true}).ok,false,'the existing deck is exhausted after 10 original cards');
assert.equal(instance.snapshot().count,9);
assert.ok(!Object.keys(instance).includes('discard'),'voluntary discard must not be exposed');
const last=instance.snapshot().classes.find(c=>c.id==='warrior').top;
assert.equal(instance.playTop('warrior',last.instance).ok,true);
assert.equal(instance.snapshot().count,8);
instance.nextTurn();
assert.equal(instance.snapshot().count,0);
assert.equal(instance.snapshot().locked,false);
assert.equal(instance.snapshot().turn,2);
assert.equal(instance.draw('warrior').ok,true);
instance.reset();
assert.equal(instance.snapshot().turn,1);
assert.equal(instance.snapshot().count,5);
console.log('PROFESSION_DECKS_OK seven_boxes five_opening ten_cap first_play_locks_draw no_discard clear_next_turn');
