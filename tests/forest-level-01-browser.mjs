import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs';
const output='artifacts/forest-level-01';
fs.mkdirSync(output,{recursive:true});
const browser=await chromium.launch({headless:true,args:['--no-sandbox','--disable-dev-shm-usage','--use-gl=angle','--use-angle=swiftshader']});
try{
 const page=await browser.newPage({viewport:{width:1920,height:1080},deviceScaleFactor:1});
 const errors=[],assets=[];
 page.on('pageerror',e=>errors.push(String(e)));
 page.on('response',r=>{if(r.url().includes('/assets/characters/farmer-faction/'))assets.push({url:r.url(),status:r.status()});});
 page.on('console',m=>{if(m.type()==='error')console.log('BROWSER_ERROR',m.text().slice(0,200));});
 await page.goto('http://127.0.0.1:4173/card-battle/forest-level-01.html',{waitUntil:'networkidle',timeout:60000});
 await page.waitForFunction(()=>!!window.__forestLevelDebug&&!!window.__forestHand&&!!window.__farmerRoster,{timeout:20000});
 const state=await page.evaluate(()=>window.__forestLevelDebug.state);
 const cells=await page.evaluate(()=>window.__forestLevelDebug.slots);
 const initial=await page.evaluate(()=>window.__forestHand.snapshot);
 assert.equal(cells.length,18);assert.equal(state.units.length,3);
 assert.equal(cells.filter(c=>c.side==='ally').length,9);
 assert.equal(cells.filter(c=>c.side==='enemy').length,9);
 assert.equal(state.units.filter(c=>c.side==='ally').length,1);
 assert.equal(initial.classes.length,7);
 assert.equal(initial.count,5);
 assert.equal(initial.hand.length,5);
 assert.equal(initial.maxHand,10);
 assert.equal(await page.locator('#class-deck-boxes .deck-pile').count(),7);
 assert.equal(await page.locator('#action-hand .action-card').count(),5);
 assert.equal(await page.locator('#class-deck-boxes .deck-pile:disabled').count(),6);
 assert.equal(await page.locator('[data-profession="warrior"] .deck-paper').count(),5,'one DOM sheet per remaining warrior deck card');
 await page.waitForTimeout(400);
 await page.screenshot({path:output+'/01-forest-3x3-and-seven-real-decks.png',fullPage:true});
 const warrior=page.locator('#class-deck-boxes button[data-profession="warrior"]');
 for(let i=0;i<5;i++)await warrior.click();
 const all=await page.evaluate(()=>window.__forestHand.snapshot);
 assert.equal(all.count,10);
 assert.equal(all.hand.length,10);
 assert.equal(await page.locator('#action-hand .action-card').count(),10);
 assert.equal(await warrior.isDisabled(),true);
 assert.equal(await page.locator('[data-profession="warrior"] .deck-paper').count(),0);
 await page.screenshot({path:output+'/02-ten-independent-playable-hand-cards.png',fullPage:true});
 const chosen=all.hand[2],last=all.hand[9];
 assert.notEqual(chosen.instance,last.instance);
 await page.locator('#action-hand .action-card[data-card-instance="'+chosen.instance+'"]').click();
 const attack=await page.evaluate(()=>window.__forestLevelDebug.attack('forest-foe-a'));
 assert.equal(attack,true);
 const after=await page.evaluate(()=>window.__forestHand.snapshot);
 assert.equal(after.count,9);
 assert.equal(after.locked,true);
 assert.ok(!after.hand.some(c=>c.instance===chosen.instance));
 assert.ok(after.hand.some(c=>c.instance===last.instance),'later-drawn card must remain after playing an arbitrary middle card');
 assert.equal(await warrior.isDisabled(),true);
 assert.equal(await page.evaluate(()=>window.__forestHand.draw('warrior').reason),'draw-locked');
 assert.equal(await page.locator('#action-hand .action-card').count(),9);
 await page.screenshot({path:output+'/03-after-playing-middle-hand-card.png',fullPage:true});
 const fx=await page.evaluate(()=>{const d=window.__forestLevelDebug;return{accepted:d.adjust(1,0,1),snapshot:d.effects}});
 assert.equal(fx.accepted,true);
 assert.ok(fx.snapshot.particleCount>0);
 await page.waitForTimeout(280);
 assert.equal((await page.evaluate(()=>window.__forestLevelDebug.effects)).busy,1);
 await page.screenshot({path:output+'/04-animated-terrain-particles.png',fullPage:true});
 await page.waitForTimeout(900);
 assert.equal((await page.evaluate(()=>window.__forestLevelDebug.effects)).busy,0);
 let played=1;
 while(played<9){
  const alive=await page.evaluate(()=>window.__forestLevelDebug.state.units.filter(x=>x.side==='enemy'&&x.alive).map(x=>x.id));
  if(!alive.length)break;
  const available=await page.evaluate(()=>window.__forestHand.snapshot.hand);
  assert.ok(available.length,'must have enough card actions for forest victory');
  const pick=available.length>2?available[1]:available[0];
  await page.locator('#action-hand .action-card[data-card-instance="'+pick.instance+'"]').click();
  assert.equal(await page.evaluate(id=>window.__forestLevelDebug.attack(id),alive[0]),true);
  played++;
 }
 assert.equal(await page.evaluate(()=>window.__forestLevelDebug.state.phase),'victory');
 assert.equal(await page.locator('#level-end').isVisible(),true);
 await page.screenshot({path:output+'/05-forest-victory.png',fullPage:true});
 await page.locator('#level-retry').click();
 assert.equal(await page.evaluate(()=>window.__forestLevelDebug.state.phase),'active');
 assert.equal(await page.evaluate(()=>window.__forestHand.snapshot.count),5);
 await page.locator('#end-hand-turn').click();
 assert.equal(await page.evaluate(()=>window.__forestHand.snapshot.count),0,'end turn must empty all remaining action cards');
 assert.equal(await page.evaluate(()=>window.__forestHand.snapshot.locked),false);
 await warrior.click();
 assert.equal(await page.evaluate(()=>window.__forestHand.snapshot.count),1);
 // User-approved characters are auto registered and accessible from the live game,
 // without violating the first level's one-friendly-unit rule.
 await page.locator('#roster-trigger').click();
 await page.waitForFunction(()=>document.querySelectorAll('#gallery-cards .roster-card img').length===3);
 await page.waitForFunction(()=>[...document.querySelectorAll('#gallery-cards img')].every(img=>img.complete&&img.naturalWidth===704),{timeout:20000});
 assert.equal(await page.locator('#gallery-cards .roster-card').count(),3);
 assert.equal(await page.locator('#gallery-cards .roster-card[data-character-id="farmer-ranger-huntress"]').count(),1);
 const registry=await page.evaluate(()=>window.__farmerRoster.characters.map(c=>({id:c.id,role:c.profession})));
 assert.ok(registry.some(c=>c.id==='farmer-ranger-huntress'&&c.role==='ranger'));
 assert.ok(registry.some(c=>c.id==='farmer-engineer-farmer'&&c.role==='engineer'));
 assert.ok(registry.some(c=>c.id==='farmer-warrior-loli-lumberjack'&&c.role==='warrior'));
 await page.screenshot({path:output+'/06-approved-farmer-roster-gallery.png',fullPage:true});
 assert.ok(assets.some(x=>x.url.endsWith('/ranger/01-huntress.png')&&x.status===200),'real huntress original image loaded successfully');
 assert.ok(assets.some(x=>x.url.endsWith('/warrior/01-loli-lumberjack.png')&&x.status===200),'real lumberjack image loaded successfully');
 await page.locator('#gallery-close').click();
 assert.deepEqual(errors,[],'no runtime page errors');
 const mobile=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1,isMobile:true,hasTouch:true});
 const mobileErrors=[];mobile.on('pageerror',e=>mobileErrors.push(String(e)));
 await mobile.goto('http://127.0.0.1:4173/card-battle/forest-level-01.html',{waitUntil:'networkidle',timeout:60000});
 await mobile.waitForFunction(()=>!!window.__forestHand&&!!window.__farmerRoster,{timeout:20000});
 assert.equal(await mobile.locator('#class-deck-boxes .deck-pile').count(),7);
 assert.equal(await mobile.locator('#action-hand .action-card').count(),5);
 await mobile.screenshot({path:output+'/07-mobile-seven-deck-boxes.png'});
 assert.deepEqual(mobileErrors,[]);
 console.log('FOREST_LEVEL_BROWSER_OK',JSON.stringify({
  cardsInitially:5,cardsFull:10,independentMiddleCardPlayed:true,
  sevenRealDecks:true,animationParticles:fx.snapshot.particleCount,
  threeRegisteredCharacters:registry.length,victory:true,mobile:true,assets,errors
 }));
}finally{await browser.close();}
