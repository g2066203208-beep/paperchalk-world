import {chromium} from 'playwright';
import fs from 'node:fs'; import path from 'node:path';
const out=path.resolve('artifacts/work-item-gallery');fs.mkdirSync(out,{recursive:true});
const coin=fs.readFileSync('site/card-battle/slots-daggers/coin-art.js','utf8');
const card=fs.readFileSync('site/card-battle/slots-daggers/coin-lab/items.html','utf8');
const src=s=>s.match(/  function metal\(nx,ny,nz,rough,ambient,lamp\) \{[\s\S]*?\n  \}/)?.[0];
if(!src(coin)||src(coin)!==src(card))throw Error('WORK METAL SHADER NOT BYTE-IDENTICAL');
if(card.includes('rotateY('+'$'+'{yaw}deg)'))throw Error('Fake CSS 3D card still in use');
const browser=await chromium.launch({headless:true,args:['--no-sandbox','--disable-dev-shm-usage','--enable-unsafe-swiftshader']});
const results=[];
for(const v of [{name:'desktop-1440x900',width:1440,height:900},{name:'phone-390x844',width:390,height:844},{name:'phone-landscape-844x390',width:844,height:390}]){
 const ctx=await browser.newContext({viewport:{width:v.width,height:v.height},deviceScaleFactor:1,recordVideo:{dir:out,size:{width:v.width,height:v.height}}});
 const page=await ctx.newPage(),errors=[];
 page.on('pageerror',e=>errors.push(String(e)));page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
 await page.goto('http://127.0.0.1:4173/card-battle/slots-daggers/coin-lab/items.html',{waitUntil:'domcontentloaded'});
 await page.waitForFunction(()=>window.WorkCard3DQA?.state().ready&&window.WorkCard3DQA?.state().artwork,{timeout:25000});
 await page.waitForTimeout(650);
 const initial=await page.evaluate(()=>WorkCard3DQA.state());
 if(initial.geometryVertices!==192||initial.geometryFaces!==162||initial.spriteOpaque<8000||initial.shaderScale!==380)throw Error('REAL MESH / PIXEL SHADER INVALID: '+JSON.stringify(initial));
 if(await page.locator('.pick').count()!==6)throw Error('Missing six original portrait cards');
 await page.screenshot({path:path.join(out,v.name+'-01-genuine-work-card-front.png'),fullPage:true});
 await page.locator('#item-doctor').click();
 await page.waitForFunction(()=>WorkCard3DQA.state().selected==='doctor'&&WorkCard3DQA.state().artwork,{timeout:15000});
 await page.waitForTimeout(250);
 await page.screenshot({path:path.join(out,v.name+'-02-doctor-original-portrait.png'),fullPage:true});
 await page.locator('#auto').click();
 await page.locator('#yaw').evaluate(el=>{el.value='87';el.dispatchEvent(new Event('input',{bubbles:true}))});
 await page.waitForTimeout(350);
 const edge=await page.evaluate(()=>WorkCard3DQA.state());
 if(Math.abs(edge.yaw-87)>1||edge.spriteOpaque<1000)throw Error('SIDE ROTATION FAILED '+JSON.stringify(edge));
 await page.screenshot({path:path.join(out,v.name+'-03-actual-3d-card-side-edge.png'),fullPage:true});
 await page.locator('#flip').click();await page.waitForTimeout(380);
 const reverse=await page.evaluate(()=>WorkCard3DQA.state());
 if(reverse.side!=='back')throw Error('REVERSE FACE GEOMETRY FAILED '+JSON.stringify(reverse));
 await page.screenshot({path:path.join(out,v.name+'-04-actual-3d-card-reverse.png'),fullPage:true});
 await page.locator('#reset').click();
 const reset=await page.evaluate(()=>WorkCard3DQA.state());
 if(Math.abs(reset.yaw+18)>1||errors.length)throw Error('RESET / PAGE ERRORS '+JSON.stringify({reset,errors}));
 results.push({name:v.name,initial,edge,reverse,reset,errors});
 console.log('PASS',v.name,JSON.stringify({initial,edge,reverse,reset}));
 await ctx.close();
}
await browser.close();
fs.writeFileSync(path.join(out,'results.json'),JSON.stringify({sourceMetalIdentical:true,results},null,2));