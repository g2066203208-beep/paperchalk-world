import {chromium} from 'playwright';
import fs from 'node:fs';import path from 'node:path';
const out=path.resolve('artifacts/work-item-gallery');
fs.mkdirSync(out,{recursive:true});
const coinSource=fs.readFileSync('site/card-battle/slots-daggers/coin-art.js','utf8');
const cardSource=fs.readFileSync('site/card-battle/slots-daggers/coin-lab/card-probe.js','utf8');
const metal=s=>s.match(/  function metal\(nx,ny,nz,rough,ambient,lamp\) \{[\s\S]*?\n  \}/)?.[0];
if(!metal(coinSource)||metal(coinSource)!==metal(cardSource))throw Error('native Work metal() shader changed');
const pageSource=fs.readFileSync('site/card-battle/slots-daggers/coin-lab/index.html','utf8');
if(!pageSource.includes('id="objectPicker"')||!pageSource.includes('id="coin-pane"')||!pageSource.includes('id="card-pane"'))throw Error('03 is not the unified page');
if(pageSource.includes('href="./items.html"'))throw Error('separate 04 page still in primary navigation');
const cases=[{id:'desktop-1440x900',width:1440,height:900},{id:'phone-portrait-390x844',width:390,height:844},{id:'phone-landscape-844x390',width:844,height:390}];
const browser=await chromium.launch({headless:true,args:['--no-sandbox','--disable-dev-shm-usage','--enable-unsafe-swiftshader']});
const results=[];
for(const v of cases){
 const bc=await browser.newContext({viewport:{width:v.width,height:v.height},deviceScaleFactor:1,recordVideo:{dir:out,size:{width:v.width,height:v.height}}});
 const page=await bc.newPage(),errors=[];
 page.on('pageerror',e=>errors.push(String(e)));
 page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
 await page.goto('http://127.0.0.1:4173/card-battle/slots-daggers/coin-lab/index.html',{waitUntil:'domcontentloaded'});
 try{
  await page.waitForFunction(()=>!!window.WorkMuseumQA&&!!window.WorkCoin3DQA&&!!window.WorkCardProbe,{timeout:24000});
  await page.waitForTimeout(650);
  let initial=await page.evaluate(()=>({museum:WorkMuseumQA.state(),coin:WorkCoin3DQA.state()}));
  console.log('GOLD BASELINE',v.id,JSON.stringify(initial));
  if(initial.museum.selected!=='coin'||initial.museum.count!==7||initial.museum.coinVisible!==true||initial.museum.cardVisible!==false)throw Error('coin default baseline wrong');
  if(initial.coin.sourceParity.differentChannels!==0||initial.coin.vertices!==60)throw Error('gold renderer baseline changed');
  if(await page.locator('#objectPicker button').count()!==7)throw Error('coin+6 cards not available on 03');
  await page.screenshot({path:path.join(out,v.id+'-01-gold-unified-original-03.png'),fullPage:true});
  await page.locator('#object-hunter').click();
  await page.waitForFunction(()=>WorkMuseumQA.state().selected==='hunter'&&WorkMuseumQA.state().cardReady&&WorkMuseumQA.state().artwork,{timeout:20000});
  await page.waitForTimeout(220);
  const hunter=await page.evaluate(()=>WorkMuseumQA.state());
  if(hunter.coinVisible!==false||hunter.cardVisible!==true||hunter.vertices!==192||hunter.faces!==162||hunter.painted<6000)throw Error('actual card mesh or art missing '+JSON.stringify(hunter));
  if(Math.abs(hunter.meshAspect-2/3)>.01)throw Error('card model distorts original 1024×1536 artwork '+JSON.stringify(hunter));
  const isPortrait=v.width<780;
  if(hunter.canvasSize[0] !== (isPortrait?540:820)||hunter.canvasSize[1] !== (isPortrait?650:620))throw Error('mobile frame does not adapt '+JSON.stringify(hunter));
  await page.screenshot({path:path.join(out,v.id+'-02-full-art-minimal-3d-character-card.png'),fullPage:true});
  await page.locator('#object-doctor').click();
  await page.waitForFunction(()=>WorkMuseumQA.state().selected==='doctor'&&WorkMuseumQA.state().cardReady&&WorkMuseumQA.state().artwork,{timeout:20000});
  await page.locator('#cardAuto').click();
  await page.locator('#cardYaw').evaluate(el=>{el.value='87';el.dispatchEvent(new Event('input',{bubbles:true}));});
  await page.waitForTimeout(150);
  const side=await page.evaluate(()=>WorkMuseumQA.state());
  if(Math.abs(side.yaw-87)>1||side.painted<500)throw Error('physical card edge test invalid '+JSON.stringify(side));
  await page.screenshot({path:path.join(out,v.id+'-03-physical-thin-edge.png'),fullPage:true});
  await page.locator('#cardFlip').click();
  await page.waitForTimeout(150);
  const back=await page.evaluate(()=>WorkMuseumQA.state());
  if(!back.back)throw Error('real reverse face not reached '+JSON.stringify(back));
  await page.locator('#cardReset').click();
  await page.locator('#cardFlip').click();
  await page.waitForTimeout(150);
  await page.screenshot({path:path.join(out,v.id+'-04-reverse-card-stamped.png'),fullPage:true});
  await page.locator('#object-coin').click();
  await page.waitForTimeout(150);
  const after=await page.evaluate(()=>WorkMuseumQA.state());
  if(!after.coinVisible||after.cardVisible||after.selected!=='coin')throw Error('failed returning to same original 03 coin');
  if(errors.length)throw Error('Browser JS error: '+errors.join(' | '));
  results.push({viewport:v.id,initial,hunter,side,back,after,errors});
  console.log('PASS',v.id,JSON.stringify({hunter,side,back,after}));
 }catch(e){
  console.log('FAIL',v.id,String(e),JSON.stringify(errors));
  await page.screenshot({path:path.join(out,v.id+'-00-failure-debug.png'),fullPage:true}).catch(()=>{});
  throw e;
 }finally{await bc.close();}
}
const legacy=await browser.newPage();
await legacy.goto('http://127.0.0.1:4173/card-battle/slots-daggers/coin-lab/items.html',{waitUntil:'domcontentloaded'});
await legacy.waitForURL('**/coin-lab/index.html?item=hunter',{timeout:15000});
await legacy.waitForFunction(()=>window.WorkMuseumQA?.state().selected==='hunter'&&window.WorkMuseumQA?.state().cardReady,{timeout:18000});
results.push({legacyRedirect:true,url:legacy.url()});await legacy.close();
await browser.close();
fs.writeFileSync(path.join(out,'results.json'),JSON.stringify({shaderIdentical:true,results},null,2));