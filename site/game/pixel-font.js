export function bitmapForText(str){
  const glyphs=[...str];
  const cols=[];let advance=0;
  for(const char of glyphs){
    if(char===' '){advance+=7;continue}
    const hex=PIXEL_CJK_16[char];
    if(!hex||hex.length!==64)return null;
    for(let row=0;row<16;row++){
      const bits=parseInt(hex.slice(row*4,row*4+4),16);
      for(let x=0;x<16;x++)if(bits&(0x8000>>>x))cols.push([advance+x,row])
    }
    advance+=17;
  }
  return {w:Math.max(0,advance-1),h:16,cols};
}
